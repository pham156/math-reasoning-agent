#!/usr/bin/env bash
set -euo pipefail
cd /home/pham156/math-reasoning-agent
source scripts/setup_env.sh >/dev/null

export APPTAINER_CACHEDIR="$CACHE_DIR/apptainer"
export APPTAINER_TMPDIR="$CACHE_DIR/apptainer_tmp"
mkdir -p "$APPTAINER_CACHEDIR" "$APPTAINER_TMPDIR" "$TMPDIR" "$CACHE_DIR/pip"
SMOKE_IMAGE="${RL_SMOKE_IMAGE:-$SCRATCH_ROOT/containers/rl-smoke-python311.sif}"
SMOKE_PYTHON="${RL_SMOKE_PYTHON:-$SCRATCH_ROOT/env/rl-smoke/bin/python}"
GPU_ARGS=()
if [[ "${RL_SMOKE_GPU:-0}" == 1 ]]; then
  GPU_ARGS=(--nv)
fi
exec apptainer exec --cleanenv --no-home "${GPU_ARGS[@]}" \
  --bind "$PROJECT_ROOT:$PROJECT_ROOT" \
  --bind "$SCRATCH_ROOT:$SCRATCH_ROOT" \
  --bind "$TMPDIR:/tmp" \
  --env "PROJECT_ROOT=$PROJECT_ROOT,SCRATCH_ROOT=$SCRATCH_ROOT,MODEL_DIR=$MODEL_DIR,DATA_DIR=$DATA_DIR,OUTPUT_DIR=$OUTPUT_DIR,CACHE_DIR=$CACHE_DIR" \
  --env "HF_HOME=$HF_HOME,HF_HUB_CACHE=$HF_HOME/hub,HF_DATASETS_CACHE=$HF_DATASETS_CACHE,TORCH_HOME=$TORCH_HOME,TMPDIR=$TMPDIR" \
  --env "PIP_CACHE_DIR=$CACHE_DIR/pip,XDG_CACHE_HOME=$CACHE_DIR/xdg,CUDA_CACHE_PATH=$CACHE_DIR/cuda,TRITON_CACHE_DIR=$CACHE_DIR/triton" \
  --env "PYTHONPATH=$PROJECT_ROOT,PYTHONNOUSERSITE=1,PYTHONDONTWRITEBYTECODE=1,OMP_NUM_THREADS=1,OPENBLAS_NUM_THREADS=1" \
  --env "CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES:-}" \
  --env "CUBLAS_WORKSPACE_CONFIG=:16:8,CUDA_LAUNCH_BLOCKING=1,FLASH_ATTENTION_DETERMINISTIC=1" \
  --env "HF_HUB_DISABLE_IMPLICIT_TOKEN=1,HF_HUB_DISABLE_XET=1,SLURM_JOB_ID=${SLURM_JOB_ID:-},SLURM_ARRAY_TASK_ID=${SLURM_ARRAY_TASK_ID:-}" \
  "$SMOKE_IMAGE" "$SMOKE_PYTHON" "$@"
